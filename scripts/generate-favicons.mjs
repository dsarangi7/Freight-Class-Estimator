/**
 * Generate green "fc" truck/box mark favicons + OG image with sharp.
 * Run: npm run favicons
 */
import sharp from "sharp";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const pub = join(__dirname, "..", "public");
const icons = join(pub, "icons");
mkdirSync(icons, { recursive: true });

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <rect width="512" height="512" rx="96" fill="#16a34a"/>
  <g fill="#ffffff">
    <!-- simple box -->
    <rect x="96" y="160" width="200" height="160" rx="16" opacity="0.95"/>
    <path d="M96 200h200" stroke="#bbf7d0" stroke-width="12" fill="none"/>
    <!-- truck cab hint -->
    <rect x="300" y="200" width="116" height="120" rx="16"/>
    <rect x="330" y="220" width="56" height="44" rx="8" fill="#16a34a"/>
    <circle cx="200" cy="340" r="28"/>
    <circle cx="360" cy="340" r="28"/>
  </g>
  <text x="256" y="130" text-anchor="middle" font-family="system-ui,Segoe UI,Arial,sans-serif"
        font-size="72" font-weight="700" fill="#ffffff" letter-spacing="-2">fc</text>
</svg>`;

writeFileSync(join(pub, "favicon.svg"), svg);

const base = sharp(Buffer.from(svg));

async function png(size, out) {
  await sharp(Buffer.from(svg)).resize(size, size).png().toFile(out);
}

await png(16, join(pub, "favicon-16x16.png"));
await png(32, join(pub, "favicon-32x32.png"));
await png(180, join(pub, "apple-touch-icon.png"));
await png(192, join(icons, "android-chrome-192x192.png"));
await png(512, join(icons, "android-chrome-512x512.png"));
await png(180, join(icons, "apple-touch-icon.png"));
await png(16, join(icons, "favicon-16x16.png"));
await png(32, join(icons, "favicon-32x32.png"));
await png(150, join(icons, "mstile-150x150.png"));

// multi-size ICO (32 + 16)
const ico32 = await sharp(Buffer.from(svg)).resize(32, 32).png().toBuffer();
const ico16 = await sharp(Buffer.from(svg)).resize(16, 16).png().toBuffer();
// Use 32png as favicon.ico fallback (browsers accept PNG-in-ICO poorly; write 32 png copied as ico via sharp)
await sharp(ico32).toFile(join(pub, "favicon.ico"));

// OG image 1200×630
const ogSvg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="#fafafa"/>
  <rect x="0" y="0" width="12" height="630" fill="#16a34a"/>
  <text x="80" y="220" font-family="system-ui,Segoe UI,Arial,sans-serif" font-size="64" font-weight="700" fill="#171717">Freight Class Estimator</text>
  <text x="80" y="300" font-family="system-ui,Segoe UI,Arial,sans-serif" font-size="32" fill="#4d4d4d">Density → NMFC-style class · Multi-pallet · Free</text>
  <text x="80" y="520" font-family="system-ui,Segoe UI,Arial,sans-serif" font-size="24" fill="#8f8f8f">freightclassestimator.com · Educational estimate only</text>
</svg>`;
await sharp(Buffer.from(ogSvg)).png().toFile(join(pub, "og-default.png"));

writeFileSync(
  join(icons, "README-favicons.txt"),
  "Generated by scripts/generate-favicons.mjs — green fc truck/box mark.\n",
);

console.log("Favicons + OG written to public/");
